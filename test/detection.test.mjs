import { test } from "node:test";
import assert from "node:assert/strict";
import { page, disclosure, plain } from "./helpers.mjs";

const { SteamUnslop } = page();
const analyze = text => SteamUnslop.analyze(disclosure(text));
const keys = r => plain(r.hints.map(h => h.key));

test("qualified art and translation is lowered and marked uncertain", () => {
  const info = analyze(
    "No AI-generated output has been used as-is in the visual assets. AI generation tools were used only as a starting point for some visual assets, and every one of them was edited, composited, retouched, or remodeled by our art team.<br>- Item icons<br>- Some character weapon 3D models, where AI tools were used only in the early stages of production<br>The Japanese version uses AI-assisted translation as a provisional measure.<br>No AI-generated content is created during gameplay.",
  );
  assert.deepEqual(plain(info.tags), ["art", "model", "transl"]);
  const r = SteamUnslop.rate(info);
  assert.equal(r.rawLevel, 3);
  assert.equal(r.level, 2);
  assert.ok(r.uncertain && r.lowered);
  assert.deepEqual(keys(r), ["rework", "start", "temp", "part"]);
});

test("negated clauses do not count", () => {
  const info = analyze(
    "An AI-assisted tool was used to create a preliminary translation pass that was reviewed by human localization professionals.<br>AI was not and will not be used to generate in-game art, audio, narrative, or gameplay elements.",
  );
  assert.deepEqual(plain(info.tags), ["transl"]);
  assert.equal(SteamUnslop.rate(info).level, 1);
});

test("'but not' splits clauses, 'not only' is no negation", () => {
  assert.deepEqual(
    plain(analyze("We used AI for translation, but not for any art or music.").tags),
    ["transl"],
  );
  assert.deepEqual(
    plain(analyze("AI was used not only for textures but also for voice lines.").tags),
    ["art", "voice"],
  );
});

test("concept art counts as concept", () => {
  assert.deepEqual(plain(analyze("Some concept art was created with AI.").tags), ["idea"]);
});

test("live AI is never lowered", () => {
  const r = SteamUnslop.rate(
    analyze(
      "NPC dialogue is generated in real-time using a large language model. All prompts were reviewed by our team.",
    ),
  );
  assert.equal(r.level, 3);
  assert.ok(r.uncertain);
});

test("positive 'as-is' is not treated as rework", () => {
  const r = SteamUnslop.rate(
    analyze("The game uses AI-generated images as-is for all card illustrations."),
  );
  assert.equal(r.level, 2);
  assert.equal(r.uncertain, false);
});

test("German disclosure texts", () => {
  assert.deepEqual(
    plain(
      analyze("Die Texte wurden mit KI \u00fcbersetzt. Grafiken wurden nicht mit KI erstellt.")
        .tags,
    ),
    ["transl"],
  );
});

test("text keeps paragraphs and stops at the next heading", () => {
  const info = analyze("First line.<br><br>Second line.");
  assert.equal(info.text, "First line.\nSecond line.");
});

test("pages without disclosure return null", () => {
  assert.equal(SteamUnslop.analyze("<h2>About this game</h2><p>No AI here.</p>"), null);
});

test("denial with stock assets: no usage tags, marked as denied and unintended", () => {
  const info = analyze(
    "We do NOT use AI-generated art, and we never intentionally include AI assets in our game. We sometimes purchase assets and use stock photos. We do our best to verify them, but nowadays, distinguishing AI from human-made art can be hard.<br>That said, if there is any specific artwork that you believe looks like AI or raises concerns, we would appreciate it if you could point it out on our Discord server. We will investigate and replace anything that might have slipped through.<br>AI-generated art is NOT something we want to include in our game.",
  );
  assert.deepEqual(plain(info.tags), []);
  const r = SteamUnslop.rate(info);
  assert.equal(r.level, 0);
  assert.deepEqual(keys(r), ["denied", "unintended"]);
});

test("hypothetical clauses do not hide real use", () => {
  assert.deepEqual(
    plain(
      analyze("If you talk to an NPC, its answers are generated by a large language model.").tags,
    ),
    ["live"],
  );
  assert.deepEqual(
    plain(
      analyze(
        "Character portraits were generated with AI. Report anything that looks off on Discord.",
      ).tags,
    ),
    ["art"],
  );
  const r = SteamUnslop.rate(
    analyze("Character portraits were generated with AI. We did not use AI for music."),
  );
  assert.ok(!keys(r).includes("denied"), "partial negation is no denial");
});

test("human-made statements are no usage; optional live AI stays high", () => {
  const info = analyze(
    "All of our quests are written by human authors, and all of our art and music are created by human artists and musicians. During play, an optional AI Dungeon Master narrates the story: its narration, character dialogue and item descriptions are generated live by language models and read aloud with text-to-speech, in response to what your party types on their phones. You can disable the AI Dungeon Master and replace it with a Player Dungeon Master.<br>Stellt eine Verbindung zu einem Drittanbieter zur Erstellung von KI-Inhalten her: OpenAI GPT-4.1 (text); Inworld and OpenAI text-to-speech (voice)",
  );
  assert.deepEqual(plain(info.tags), ["live", "voice", "text"]);
  const r = SteamUnslop.rate(info);
  assert.equal(r.level, 3);
  assert.deepEqual(keys(r), ["optional"]);
});

test("human rework of AI output still counts as usage", () => {
  const info = analyze("Backgrounds were generated with AI and painted over by human artists.");
  assert.deepEqual(plain(info.tags), ["art"]);
  assert.ok(keys(SteamUnslop.rate(info)).includes("rework"));
  const only = analyze("All character art is hand-drawn by our team.");
  assert.deepEqual(plain(only.tags), []);
  assert.deepEqual(keys(SteamUnslop.rate(only)), ["denied"]);
});

test("AI upscaling of existing video counts as video and upscaling, lowered and uncertain", () => {
  const info = analyze(
    "AI was used to upscale the resolution and framerate of the master full-motion video source material, enhancing the full-motion cinematics for an optional enhanced viewing experience.",
  );
  assert.deepEqual(plain(info.tags), ["video", "upscale"]);
  const r = SteamUnslop.rate(info);
  assert.equal(r.rawLevel, 2);
  assert.equal(r.level, 1);
  assert.deepEqual(keys(r), ["upscale", "optional"]);
});

test("'video game' is no video content", () => {
  assert.deepEqual(plain(analyze("This video game uses AI-generated character portraits.").tags), [
    "art",
  ]);
});

test("AI-written code with public-domain artwork is code only", () => {
  const info = analyze(
    "AI tools were used in writing the game's code. No AI generated images, music, audio, or models were used. All artwork is Public-Domain paintings from famous, historical artists.",
  );
  assert.deepEqual(plain(info.tags), ["code"]);
  assert.equal(SteamUnslop.rate(info).level, 1);
});

test("'with reference to AI' is no reference material, translated store text is translation", () => {
  const info = analyze(
    "I create a small portion of the code with reference to AI.<br>I use AI for translating the store text.",
  );
  assert.deepEqual(plain(info.tags), ["transl", "code"]);
  assert.ok(!keys(SteamUnslop.rate(info)).includes("start"));
});

test("text that was only translated is translation, not written content", () => {
  for (const s of [
    "Text translation.",
    "AI was used for the translation of the dialogues.",
    "All texts were machine translated with DeepL.",
    "We used AI translating the in-game text and the store description.",
  ])
    assert.deepEqual(plain(analyze(s).tags), ["transl"], s);
  assert.equal(SteamUnslop.rate(analyze("Text translation.")).level, 1);
  assert.deepEqual(plain(analyze("Die Texte wurden teilweise mit KI \u00fcbersetzt.").tags), [
    "transl",
  ]);
  assert.deepEqual(
    plain(analyze("AI wrote the dialogues and translated them.").tags),
    ["text", "transl"],
    "written dialogue still counts",
  );
});

test("upscaling is its own kind of use, so upscale-only disclosures are not unclear", () => {
  const only = analyze("AI was used for upscaling.");
  assert.deepEqual(plain(only.tags), ["upscale"]);
  assert.equal(SteamUnslop.rate(only).level, 1);
  const video = analyze("AI was used to upscale the resolution of the full-motion video.");
  assert.deepEqual(plain(video.tags), ["video", "upscale"]);
  assert.equal(
    SteamUnslop.rate(video).level,
    1,
    "medium, lowered as only existing material was upscaled",
  );
  assert.deepEqual(
    plain(analyze("The game features enhanced gameplay made with AI-generated art.").tags),
    ["art"],
    "'enhanced' alone is no upscaling",
  );
});

test("a use named after an exception counts, an excluded one does not", () => {
  const tagsOf = text => plain(analyze(text).tags);

  assert.deepEqual(tagsOf("No AI was used except for the voice acting."), ["voice"]);
  assert.deepEqual(tagsOf("Nothing in the game is AI generated, apart from the translations."), [
    "transl",
  ]);
  assert.deepEqual(tagsOf("Keine KI, au\u00dfer bei der \u00dcbersetzung."), ["transl"]);
  assert.deepEqual(tagsOf("We used AI for all textures except the character portraits."), ["art"]);
  assert.deepEqual(tagsOf("Besides the art, AI was also used for the music."), ["art", "music"]);

  const denial = analyze("No generative AI was used in the final product.");
  assert.deepEqual(plain(denial.tags), []);
  assert.deepEqual(keys(SteamUnslop.rate(denial)), ["denied"]);
});

test("AI assets replaced by the team lower the level, assets replaced by AI do not", () => {
  const replacedByTeam = analyze(
    "Generative AI technology is used in a supplementary capacity during the creation of some 2D prop assets.<br>" +
      "Any such assets are replaced through our production pipeline by our art and development teams, " +
      "ensuring they meet our quality standards and creative direction.",
  );
  const rating = SteamUnslop.rate(replacedByTeam);
  assert.equal(rating.rawLevel, 2);
  assert.equal(rating.level, 1);
  assert.ok(keys(rating).includes("temp"));

  const german = SteamUnslop.rate(
    analyze("KI-Grafiken werden vor dem Release durch unser Art-Team ersetzt."),
  );
  assert.equal(german.level, 1);

  for (const text of [
    "Die Sprecher wurden durch KI-Stimmen ersetzt.",
    "AI-generated music replaced our old soundtrack.",
  ]) {
    assert.equal(SteamUnslop.rate(analyze(text)).lowered, false, text);
  }
});

test("human work described with adjectives is no AI use", () => {
  const info = analyze(
    "We only used AI to translate the game into more languages.<br>Nothing else is AI.<br>" +
      "All 3D models and animations are made by our talented team of real human artists.<br>" +
      "All in-game music was made by real people and licensed via Artlist.io (Artlist Originals, no AI).",
  );
  assert.deepEqual(plain(info.tags), ["transl"]);
  assert.equal(SteamUnslop.rate(info).level, 1);

  const aiSystem = analyze("The voices were made by our AI voice system.");
  assert.deepEqual(plain(aiSystem.tags), ["voice"], "an AI system is no human team");
});
