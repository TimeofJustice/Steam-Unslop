// Builds the core bundle and the platform outputs.
//   dist/core.js                                        core, bundled from src/core/main.js
//   dist/extension/                                     unpacked browser extension
//   platforms/millennium/webview/core.js                core for the Millennium webview
//   platforms/millennium/frontend/strings.generated.ts  Millennium settings texts
import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  rmSync,
  readdirSync,
  cpSync,
  existsSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const readFile = path => readFileSync(join(repositoryRoot, path), "utf8");

function writeFile(path, content) {
  mkdirSync(dirname(join(repositoryRoot, path)), { recursive: true });
  writeFileSync(join(repositoryRoot, path), content);
}

const toJson = value => JSON.stringify(value, null, 2) + "\n";

const { version } = JSON.parse(readFile("package.json"));

const localesByLanguage = Object.fromEntries(
  readdirSync(join(repositoryRoot, "src/locales"))
    .filter(fileName => fileName.endsWith(".json"))
    .map(fileName => [
      fileName.replace(/\.json$/, ""),
      JSON.parse(readFile(`src/locales/${fileName}`)),
    ]),
);

const localeSection = section =>
  Object.fromEntries(
    Object.entries(localesByLanguage).map(([language, locale]) => [language, locale[section]]),
  );

// Core bundle. It carries the license header once; the source comments are left out.
const LICENSE_HEADER =
  "// Copyright 2026 Jonas Oelschner (TimeofJustice). Part of Steam Unslop, https://github.com/TimeofJustice/Steam-Unslop\n" +
  "// SPDX-License-Identifier: Apache-2.0\n";

const { outputFiles } = await build({
  entryPoints: [join(repositoryRoot, "src/core/main.js")],
  bundle: true,
  write: false,
  format: "iife",
  target: "chrome110",
  loader: { ".css": "text" },
  charset: "utf8",
  legalComments: "none",
});

// Loaded twice (e.g. by two wrappers), the second copy does nothing.
const core = `${LICENSE_HEADER}// Steam Unslop ${version}, built by scripts/build.mjs from src/core, do not edit.
// Platform wrappers call SteamUnslop.hold() early and SteamUnslop.start(storage) once the DOM is ready,
// with storage = { load(key), save(key, value), remove(keys) }.
(() => {
if (globalThis.SteamUnslop) return;

${outputFiles[0].text}})();
`;
writeFile("dist/core.js", core);

// Browser extension
rmSync(join(repositoryRoot, "dist/extension"), { recursive: true, force: true });

const manifest = JSON.parse(readFile("platforms/extension/manifest.json"));
manifest.version = version;
writeFile("dist/extension/manifest.json", toJson(manifest));

for (const fileName of ["content.js", "popup.html", "popup.js"]) {
  writeFile(`dist/extension/${fileName}`, readFile(`platforms/extension/${fileName}`));
}

// Apache 2.0: the license and the NOTICE file travel with every copy.
for (const fileName of ["LICENSE", "NOTICE"]) {
  writeFile(`dist/extension/${fileName}`, readFile(fileName));
}

writeFile("dist/extension/core.js", core);

const iconFolder = join(repositoryRoot, "platforms/extension/icons");
if (existsSync(iconFolder)) {
  cpSync(iconFolder, join(repositoryRoot, "dist/extension/icons"), { recursive: true });
}

for (const [language, locale] of Object.entries(localesByLanguage)) {
  const levelOptionMessages = Object.fromEntries(
    locale.ui.minLevelOptions.map((option, level) => [
      `minLevelOption${level}`,
      { message: option },
    ]),
  );

  writeFile(
    `dist/extension/_locales/${language}/messages.json`,
    toJson({
      extName: { message: locale.extension.name },
      extDesc: { message: locale.extension.description },
      settingsHint: { message: locale.extension.settingsHint },
      minLevel: { message: locale.ui.minLevel },
      ...levelOptionMessages,
    }),
  );
}

// Millennium plugin
writeFile("platforms/millennium/webview/core.js", core);

const millenniumStrings = JSON.stringify(localeSection("millennium"), null, 2);
writeFile(
  "platforms/millennium/frontend/strings.generated.ts",
  `${LICENSE_HEADER}// Generated by scripts/build.mjs from src/locales, do not edit.\nexport const STRINGS = ${millenniumStrings} as const;\n`,
);

const millenniumToml = readFile("platforms/millennium/millennium.toml");
writeFile(
  "platforms/millennium/millennium.toml",
  millenniumToml.replace(/^version = ".*"$/m, `version = "${version}"`),
);

console.log(
  `Built ${version}: dist/core.js, dist/extension/, platforms/millennium/webview/core.js`,
);
